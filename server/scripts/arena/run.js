// The arena: replays learner histories through every knowledge model and scores their predictions on learners the
// model never trained on. Every attempt is predicted BEFORE its result is learned.
//
//   npm run arena                                   all 5 simulated worlds, 3 seeds, 500 learners each   (writes docs/arena-results.md)
//   npm run arena -- --quick                        2 worlds, 1 seed, 200 learners (a fast check, writes nothing)
//   npm run arena -- --source mongo                 real learner logs from the database
//   options: --worlds W0-static,W4-realistic  --seeds 3  --learners 500
//
// IMPORTANT: results on simulated worlds say how the MODELS behave when a given effect is (or is not) in the data.
// They say nothing about how well they would do on real people.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { KINDS, aggregate, markdownTable, runDataset } from "./core.js";
import { loadFromMongo } from "./dataset-mongo.js";
import { WORLDS, simulate } from "./sim.js";

const flag = (name) => process.argv.includes(`--${name}`);
const value = (name, fallback) => { const i = process.argv.indexOf(`--${name}`); return i >= 0 && process.argv[i + 1] && !process.argv[i + 1].startsWith("--") ? process.argv[i + 1] : fallback; };

const quick = flag("quick");
const seeds = Number(value("seeds", quick ? 1 : 3)), learners = Number(value("learners", quick ? 200 : 500));
const worldArg = value("worlds", quick ? "W0-static,W4-realistic" : "all");
const names = worldArg === "all" ? Object.keys(WORLDS) : worldArg.split(",");
const started = Date.now();

if (value("source", "sim") === "mongo") {
  const data = await loadFromMongo();
  const events = data.sequences.reduce((n, s) => n + s.events.length, 0);
  console.log(`real data: ${data.rawSubmissions} Submit rows -> ${data.sequences.length} learners with 2+ problems, ${events} first-Submit outcomes`);
  if (data.sequences.length < 10) {
    console.log("Too few learners to evaluate anything yet (about 10 are needed to run; 30-50 for a first look). The pipeline works: collect more data.");
  } else {
    console.log(markdownTable(aggregate([runDataset(data)])));
  }
  process.exit(0);
}

const sections = [];
for (const name of names) {
  if (!WORLDS[name]) { console.error(`unknown world ${name}; choose from: ${Object.keys(WORLDS).join(", ")}`); process.exit(1); }
  const perSeed = [];
  for (let seed = 1; seed <= seeds; seed++) {
    perSeed.push(runDataset(simulate(name, { learners, seed })));
    process.stdout.write(`  ${name} seed ${seed}/${seeds} done\n`);
  }
  const table = aggregate(perSeed), sizes = perSeed[0].sizes;
  sections.push({ name, table, sizes });
  console.log(`\n=== ${name}  (${sizes.train}/${sizes.valid}/${sizes.test} learners train/valid/test, about ${sizes.testEvents} exam attempts per seed)`);
  console.log(markdownTable(table));
}

if (!quick) {
  const out = fileURLToPath(new URL("../../../docs/arena-results.md", import.meta.url));
  const md = [
    "# Arena results: how the knowledge models compare",
    "",
    `Generated by \`npm run arena\` (${new Date().toISOString().slice(0, 10)}): ${seeds} random seeds x ${learners} simulated learners per world, ${Math.round((Date.now() - started) / 1000)} s.`,
    "",
    "**Read this first.** These learners are SIMULATED (`server/scripts/arena/sim.js`). Each world switches certain behaviours of the hidden true skill on or off, so we can check that each model idea helps when its effect exists and does not hurt when it does not. The numbers say nothing about how good any model would be on REAL people; that needs the real logs (`npm run arena -- --source mongo`).",
    "",
    "How to read the tables: every attempt is predicted before its result is learned, on learners the model never trained on. Lower log-loss is better (always guessing 50% scores 0.693); higher AUC is better; the calibration gap is how far \"70%\" is from the real success rate on average (lower is better). The last column is the average per-learner log-loss gain over today's Elo, with its uncertainty (a gain above about twice the uncertainty is a real difference, not luck).",
    "",
    "| world | what is switched on in the true learners |", "|---|---|",
    ...names.map((n) => { const w = WORLDS[n]; return `| ${n} | learning ${w.learning ? "yes" : "no"}, forgetting ${Number.isFinite(w.halfLife) ? `yes (half-life ${w.halfLife} days)` : "no"}, problems train ${w.multiTruth ? "several skills" : "one skill"}, ${w.correlated ? "skills correlated (an overall ability)" : "independent skills"}, problem noise ${w.itemSd}, session mood ${w.sessionSd}, ${Math.round(w.tagCorruption * 100)}% of the secondary skill tags the models see are wrong |`; }),
    "",
    ...sections.flatMap(({ name, table, sizes }) => [
      `## ${name}`, "", `${sizes.train} / ${sizes.valid} / ${sizes.test} learners (train / choose settings / exam), about ${sizes.testEvents} exam attempts per seed, averaged over ${seeds} seeds.`, "",
      markdownTable(table), "",
      "Settings chosen on the validation learners (one entry per seed):",
      ...KINDS.filter((k) => !["global-rate", "item-mean", "elo", "logreg"].includes(k)).map((k) => `- ${k}: ${table[k].params.join(" | ")}`), "",
    ]),
  ].join("\n");
  writeFileSync(out, md, "utf8");
  console.log(`\nwritten: ${out}`);
}
console.log(`\nfinished in ${Math.round((Date.now() - started) / 1000)} s`);
